import { AwsIacAnalyzer } from '../../src/core/aws-iac-analyzer.js';
import { AwsFinOpsEstimator } from '../../src/core/finops-estimator.js';
import { BedrockGuardrailsEngine } from '../../src/core/bedrock-guardrails.js';
import { AmazonBedrockProvider } from '../../src/providers/bedrock-provider.js';
import { DiffAnalyzer } from '../../src/core/diff-analyzer.js';

export interface ApiGatewayEvent {
  headers: Record<string, string>;
  body: string;
  isBase64Encoded: boolean;
}

export interface ApiGatewayResponse {
  statusCode: number;
  headers: Record<string, string>;
  body: string;
}

export async function handler(event: ApiGatewayEvent): Promise<ApiGatewayResponse> {
  try {
    const rawBody = event.isBase64Encoded
      ? Buffer.from(event.body, 'base64').toString('utf-8')
      : event.body;

    const payload = JSON.parse(rawBody || '{}');
    const githubEvent = event.headers['x-github-event'] || event.headers['X-GitHub-Event'];

    // Only process pull_request events
    if (githubEvent !== 'pull_request') {
      return {
        statusCode: 200,
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ message: `Ignored event: ${githubEvent}` })
      };
    }

    const action = payload.action;
    if (!['opened', 'synchronize', 'reopened'].includes(action)) {
      return {
        statusCode: 200,
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ message: `Action ${action} does not trigger review` })
      };
    }

    const repoName = payload.repository?.full_name || 'aws-samples/cloud-app';
    const prNumber = payload.pull_request?.number || 1;
    const diffUrl = payload.pull_request?.diff_url;

    // Fetch diff if diff_url is available
    let diffText = '';
    if (diffUrl) {
      try {
        const diffRes = await fetch(diffUrl, {
          headers: {
            'User-Agent': 'RepoPulse-AI-Bedrock-Bot',
            'Accept': 'application/vnd.github.v3.diff'
          }
        });
        if (diffRes.ok) {
          diffText = await diffRes.text();
        }
      } catch {}
    }

    // Parse diff and execute engines
    const parsedDiff = DiffAnalyzer.parseUnifiedDiff(diffText);
    const iacReport = AwsIacAnalyzer.auditDiff(parsedDiff);
    const finOpsReport = AwsFinOpsEstimator.estimateDiff(parsedDiff);
    const guardrails = new BedrockGuardrailsEngine();
    const guardResult = await guardrails.evaluate(diffText);

    // Invoke Amazon Bedrock Nova Pro for review synthesis
    const bedrock = new AmazonBedrockProvider({
      modelId: 'amazon.nova-pro-v1:0',
      region: process.env.AWS_REGION || 'us-east-1'
    });
    const review = await bedrock.reviewDiff(parsedDiff, repoName);

    // Construct Maintainer Markdown Report
    const commentMarkdown = `## ⚡ RepoPulse AI • Amazon Bedrock Maintainer Report

### 🛡️ AWS Security & Well-Architected Score: **${iacReport.securityScore} / 100**
${iacReport.executiveSummary}

### 💰 AWS FinOps Cost Delta Impact
- **Monthly Spend Impact**: \`${finOpsReport.totalMonthlySpendDelta >= 0 ? '+' : ''}$${finOpsReport.totalMonthlySpendDelta.toFixed(2)} USD/mo\`
- **Projected Annual Delta**: \`${finOpsReport.projectedAnnualDelta >= 0 ? '+' : ''}$${finOpsReport.projectedAnnualDelta.toFixed(2)} USD/yr\`
${finOpsReport.finopsRecommendations.length > 0 ? '\n**Recommendations**:\n' + finOpsReport.finopsRecommendations.map(r => `* ${r}`).join('\n') : ''}

### 🔒 Amazon Bedrock Guardrail Status: **[${guardResult.action}]**
${guardResult.isBlocked ? '⚠️ **Blocked**: Sensitive credential leaks or adversarial injection detected.' : '✅ Diff passed Bedrock zero-leak invariants.'}

### 🤖 Amazon Nova Pro Review Verdict: **[${review.status}]**
${review.maintainerExecutiveSummary}

---
*Generated by RepoPulse AI on AWS Lambda • Amazon Bedrock Converse API*`;

    return {
      statusCode: 200,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        ok: true,
        repo: repoName,
        prNumber,
        verdict: review.status,
        securityScore: iacReport.securityScore,
        costDelta: finOpsReport.totalMonthlySpendDelta,
        comment: commentMarkdown
      })
    };
  } catch (err: any) {
    return {
      statusCode: 500,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ error: err.message || 'Internal Lambda Error' })
    };
  }
}
